// Copies src/css into dist/css and generates dist/css/fonts.css + self-hosted woff2 files
// from the @fontsource packages (latin and latin-ext subsets only).
import { copyFile, mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const src = path.join(root, "src/css");
const out = path.join(root, "dist/css");
const fontsOut = path.join(out, "fonts");
const require = createRequire(import.meta.url);

/** family: the name used in tokens.css; sheets: fontsource CSS files to take faces from. */
const FONTS = [
  {
    family: "Newsreader",
    pkg: "@fontsource-variable/newsreader",
    sheets: ["opsz.css", "opsz-italic.css"],
  },
  {
    family: "Space Grotesk",
    pkg: "@fontsource/space-grotesk",
    sheets: ["400.css", "500.css", "700.css"],
  },
  {
    family: "Space Mono",
    pkg: "@fontsource/space-mono",
    sheets: ["400.css", "700.css"],
  },
];

const SUBSETS = new Set(["latin", "latin-ext"]);

async function buildFonts() {
  await mkdir(fontsOut, { recursive: true });
  const faces = [];
  for (const font of FONTS) {
    const pkgDir = path.dirname(require.resolve(`${font.pkg}/package.json`));
    for (const sheet of font.sheets) {
      const css = await readFile(path.join(pkgDir, sheet), "utf8");
      // Each face is preceded by a comment naming it, e.g. /* space-mono-latin-400-normal */
      for (const match of css.matchAll(/\/\* ([\w-]+) \*\/\s*@font-face\s*{([^}]*)}/g)) {
        const [, name, body] = match;
        const subset = name.match(/-(latin-ext|latin|[a-z]+(?:-ext)?)-(?:opsz|wght|standard|\d+)-/)?.[1];
        if (!subset || !SUBSETS.has(subset)) continue;
        const file = body.match(/url\(\.\/files\/([^)]+\.woff2)\)/)?.[1];
        if (!file) throw new Error(`No woff2 in ${font.pkg}/${sheet} (${name})`);
        await copyFile(path.join(pkgDir, "files", file), path.join(fontsOut, file));
        const keep = body
          .split(";")
          .map((d) => d.trim())
          .filter((d) => /^(font-style|font-weight|unicode-range)\b/.test(d));
        faces.push(
          `/* ${name} */\n@font-face {\n  font-family: "${font.family}";\n` +
            keep.map((d) => `  ${d};\n`).join("") +
            `  font-display: swap;\n  src: url("./fonts/${file}") format("woff2");\n}\n`,
        );
      }
    }
    await copyFile(
      path.join(pkgDir, "LICENSE"),
      path.join(fontsOut, `LICENSE-${font.family.replaceAll(" ", "-")}.txt`),
    );
  }
  if (faces.length === 0) throw new Error("No font faces generated");
  const header =
    "/* Generated by scripts/build-css.mjs from @fontsource packages. Fonts are OFL-1.1; see fonts/LICENSE-*.txt. */\n\n";
  await writeFile(path.join(out, "fonts.css"), header + faces.join("\n"));
  return faces.length;
}

await rm(out, { recursive: true, force: true });
await mkdir(out, { recursive: true });
for (const file of await readdir(src)) {
  if (file.endsWith(".css")) await copyFile(path.join(src, file), path.join(out, file));
}
const count = await buildFonts();
console.log(`css: copied stylesheets, generated ${count} font faces`);
